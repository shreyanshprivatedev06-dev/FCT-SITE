/* Generates data/sc/demand.js: deterministic synthetic demand and forecast records for the SC tower.
   Run: node tools/sc/gen-demand.js   (seeded PRNG, so the output is identical on every run)
   Values are monthly demand at standard selling price, ₹ Cr, per material (lead SKU) per month.
   Story: US generics over-forecast after two competitors launched in Aug; API exports and Nutrition
   under-forecast in Aug–Sep; the consensus plan was not re-baselined. */
const fs = require('fs'), path = require('path');
let seed = +(process.env.SEED || 237);   /* seed chosen for a clean story: stable to Jul, bias builds Aug–Sep */
const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
const NOISE_K = 2.1;   /* SKU-month error typical of a mid-maturity S&OP process (WMAPE ~12–15%) */
const noise = (pct) => 1 + (rnd() * 2 - 1) * pct * NOISE_K;

const months = ['Oct-25','Nov-25','Dec-25','Jan-26','Feb-26','Mar-26','Apr-26','May-26','Jun-26','Jul-26','Aug-26','Sep-26'];
/* family: id, name, entity, materials [id, name, base ₹ Cr], forecast drift, actual shocks by month index */
const fams = [
  { id:'USG', name:'US generics', entity:'US-01', mats:[['FG-US-4471','ER tablets 500mg',21],['FG-US-4402','Metformin XR 750mg',19],['FG-US-4519','Valsartan 160mg',17]],
    fNoise:.05, aNoise:.11, shock:{8:.98, 9:.94, 10:.80, 11:.72} },
  { id:'INF', name:'India formulations', entity:'IN-03', mats:[['FG-IN-2210','Atorvastatin 20mg',30],['FG-IN-2290','Amlodipine 5mg',26],['FG-IN-2314','Pantoprazole 40mg',22]],
    fNoise:.05, aNoise:.12, shock:{10:.97, 11:.95} },
  { id:'API', name:'API exports', entity:'IN-02', mats:[['API-L71','Losartan API',22],['API-V12','Valsartan API',18]],
    fNoise:.05, aNoise:.11, shock:{9:1.05, 10:1.15, 11:1.17} },
  { id:'NUT', name:'Nutrition', entity:'IN-06', mats:[['FG-NUT-220','Whey blend',11],['FG-NUT-310','Protein bars',9]],
    fNoise:.06, aNoise:.15, shock:{2:1.12, 10:1.06, 11:1.22} },
  { id:'SPC', name:'Specialty chemicals', entity:'IN-05', mats:[['SC-ACX-11','Acetyl derivatives',18],['SC-PYR-04','Pyridine bases',14]],
    fNoise:.05, aNoise:.13, shock:{10:.93, 11:.88} },
  { id:'LSI', name:'Life science ingredients', entity:'IN-04', mats:[['LSI-VIT-03','Vitamin B3',15],['LSI-CHO-07','Choline chloride',12]],
    fNoise:.05, aNoise:.11, shock:{} },
  { id:'EUB', name:'Europe branded', entity:'EU-01', mats:[['FG-EU-1180','Branded cardio range',13],['FG-EU-1204','Branded CNS range',10]],
    fNoise:.05, aNoise:.12, shock:{11:1.10} },
  { id:'DIS', name:'Distribution and trading', entity:'IN-08', mats:[['TR-DIS-01','Traded nutrition',14],['TR-DIS-02','Traded OTC',11]],
    fNoise:.05, aNoise:.12, shock:{} }
];
const r2 = (v) => Math.round(v * 100) / 100;
const records = [];
fams.forEach(f => f.mats.forEach(([id, name, base]) => {
  months.forEach((m, i) => {
    const trend = 1 + i * 0.006;                       /* gentle growth the plan assumes */
    const optimism = i >= 6 ? 1 + (i - 5) * 0.007 : 1;   /* plan drifts optimistic from Apr (not re-baselined) */
    const fc = base * trend * optimism * noise(f.fNoise);
    const act = base * trend * (f.shock[i] || 1) * noise(f.aNoise);
    records.push({ period:m, family:f.id, material:id, forecast:r2(fc), actual:r2(act) });
  });
}));

/* summary to tune the story: value-weighted accuracy (1 − WMAPE at material level) and bias */
const stat = (rs) => { const A = rs.reduce((s,r)=>s+r.actual,0), F = rs.reduce((s,r)=>s+r.forecast,0), E = rs.reduce((s,r)=>s+Math.abs(r.forecast-r.actual),0);
  return { acc: Math.max(0, 100*(1-E/A)).toFixed(1), bias: (100*(F-A)/A).toFixed(1) }; };
months.forEach(m => { const s = stat(records.filter(r=>r.period===m)); console.log(m, 'acc', s.acc, 'bias', s.bias); });
fams.forEach(f => { const s = stat(records.filter(r=>r.period==='Sep-26'&&r.family===f.id)); console.log('  Sep', f.id, s); });

const out = `/* FCT demo data — SC demand and forecast records (GENERATED by tools/sc/gen-demand.js; do not hand-edit).
   Monthly demand at standard selling price, ₹ Cr, per material. Seeded, so regeneration is identical. */
(function(){
const D = window.FCT_DATA; D.scx = D.scx || {};
D.scx.demand = {
  months:${JSON.stringify(months)},
  families:${JSON.stringify(fams.map(f=>({id:f.id, name:f.name, entity:f.entity, materials:f.mats.map(m=>({id:m[0], name:m[1]}))})))},
  records:[
${records.map(r=>'    '+JSON.stringify(r)).join(',\n')}
  ]
};
})();
`;
if (!process.env.DRY) fs.writeFileSync(path.join(__dirname, '../../data/sc/demand.js'), out);
console.log('wrote', records.length, 'records');
