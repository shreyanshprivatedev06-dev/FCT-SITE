/* Writes data/xtower.js: the sub-ledger balances each tower owns, by entity, at the snapshot. R2R reads them so the GL
   reconciliations for 1310 / 1410 / 2010 / 2110 tie to the O2C, SC and P2P ledgers. Run after changing any tower ledger:
     node tools/fct/sync-balances.js        (tools/fct/test-sync.js fails while the file is stale) */
const fs = require('fs'), path = require('path');
const load = require('../p2p/load.js');
const ROOT = path.join(__dirname, '../..');
const BASE = ['data/core.js','data/exceptions.js','data/p2p.js','data/o2c.js','data/r2r.js','data/sc.js','data/cmp.js','data/sc/demand.js','data/sc/anomalies.js','assets/js/fct-core.js'];
const model = (files, g)=> load(BASE.concat(files))[g];

const balances = ()=>{
  const P = model(['data/p2p/master.js','data/p2p/ledger.js','assets/js/p2p/p2p-model.js'], 'P2PM');
  const O = model(['data/o2c/master.js','data/o2c/ledger.js','assets/js/o2c/o2c-model.js'], 'O2CM');
  const S = model(['data/sc/master.js','data/sc/ledger.js','assets/js/sc/sc-model.js'], 'SCM');
  const ents = load(BASE).FCT_DATA.entities.map(e=> e.id), r2 = (v)=> Math.round((v||0)*100)/100;
  const f = (M, e)=> Object.assign({}, M.defaults, { bu:e });
  const out = { '1310':{}, '1410':{}, '2010':{}, '2110':{} };
  ents.forEach(e=>{
    out['1310'][e] = O.C.bus.some(b=> b.id===e)? r2(O.kpi('ar', f(O, e)).v) : 0;                       /* open receivables (O2C) */
    out['1410'][e] = S.C.bus.some(b=> b.id===e)? r2(S.kpi('inv', f(S, e)).v) : 0;                       /* inventory value (SC) */
    out['2010'][e] = r2(P.X.lines.filter(l=> l.e===e && l.rcv<=P.SNAP && (l.paid==null || l.paid>P.SNAP)).reduce((s,l)=> s+l.amt, 0));   /* unpaid posted invoices (P2P) */
    out['2110'][e] = r2(P.kpi('commit', f(P, e)).grni);                                                  /* goods received not invoiced (P2P) */
  });
  return out;
};
module.exports = { balances };

if(require.main === module){
  const b = balances(), tot = (a)=> Object.values(b[a]).reduce((s,v)=> s+v, 0).toFixed(2);
  const src = '/* GENERATED by tools/fct/sync-balances.js — do not edit by hand.\n   Sub-ledger balances by entity at the snapshot (₹ Cr): 1310 receivables (O2C), 1410 inventory (SC), 2010 trade payables and\n   2110 GR/IR (P2P). R2R reconciliations take their sub-ledger side from here. Totals: 1310 '+tot('1310')+' · 1410 '+tot('1410')+' · 2010 '+tot('2010')+' · 2110 '+tot('2110')+'. */\n'
    + 'window.FCT_DATA = window.FCT_DATA || {};\nwindow.FCT_DATA.subledger = '+JSON.stringify(b, null, 1).replace(/\n\s*/g, ' ')+';\n';
  fs.writeFileSync(path.join(ROOT, 'data/xtower.js'), src);
  console.log('data/xtower.js written:', ['1310','1410','2010','2110'].map(a=> a+' '+tot(a)).join(' · '));
}
